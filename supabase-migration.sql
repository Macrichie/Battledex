-- Run this in your Supabase SQL Editor (Dashboard > SQL Editor > New query)
-- Prerequisites: Enable Google auth provider in Authentication > Providers

create table battledex (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade not null,
  name text not null,
  image text not null,
  created_at timestamptz default now() not null,
  constraint battledex_user_name_unique unique (user_id, name)
);

alter table battledex enable row level security;

create policy "Users can view own fighters" on battledex
  for select to authenticated
  using ((select auth.uid()) = user_id);

create policy "Users can add own fighters" on battledex
  for insert to authenticated
  with check ((select auth.uid()) = user_id);

create policy "Users can delete own fighters" on battledex
  for delete to authenticated
  using ((select auth.uid()) = user_id);
